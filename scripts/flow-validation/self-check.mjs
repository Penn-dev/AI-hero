import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { collect } from './measure.mjs';
import { checkBody, schemaCheck } from './validate.mjs';
const root=resolve(import.meta.dirname,'../..');
const dir='reports/flow-validation/preparation/';
const registry=JSON.parse(await readFile(resolve(root,dir+'telemetry-registry.json'),'utf8'));
const r=registry.registrations[0];
const raw=await readFile(r.rolloutPath,'utf8');
const original=collect(raw,r);
if(original.status!=='PASS')throw Error('Real usage reconciliation failed');
const lines=raw.split('\n');
const index=lines.findIndex(l=>{try{return JSON.parse(l).type==='token_usage_record';}catch{return false;}});
const results=[];
const dup=collect([...lines.slice(0,index+1),lines[index],...lines.slice(index+1)].join('\n'),r);
if(dup.recordCount!==original.recordCount||dup.status!=='PASS')throw Error('Duplicate response double counted');
results.push('duplicate response not double counted');
const missing=collect(lines.filter((_,i)=>i!==index).join('\n'),r);
if(missing.status!=='HOLD')throw Error('Missing usage accepted');
results.push('missing usage record fails closed');
const record=JSON.parse(lines[index]);record.payload.thread_token_usage.total_tokens=0;
if(collect(lines.map((l,i)=>i===index?JSON.stringify(record):l).join('\n'),r).status!=='HOLD')throw Error('Invalid/reset counter accepted');
results.push('invalid/reset cumulative record fails closed');
function rejected(name,fn){let failed=false;try{fn();}catch{failed=true;}if(!failed)throw Error(name);results.push(name);}
const source='---\ntitle: "fixture"\nslug: "fixture"\ntype: "dictionary"\nupdatedAt: "2026-01-01"\n---\nUse `x`. [reference](https://example.invalid).\n\n```typescript\nconst x = TODO;\n```\n\n"Original example."\n';
checkBody(source,source);results.push('in-memory unchanged English fixture accepted');
rejected('changed TODO/fence rejected',()=>checkBody(source,source.replace('TODO','42')));
rejected('missing original natural example rejected',()=>checkBody(source,source.replace('"Original example."','')));
rejected('missing learning link rejected',()=>checkBody(source,source.replace('[reference](https://example.invalid)','reference')));
const schema=JSON.parse(await readFile(resolve(root,'content/pilots/flow-validation/inputs/common/learning.schema.json'),'utf8'));
rejected('missing required aid fields rejected',()=>schemaCheck({},schema));
const report={status:'PASS',scope:'in-memory bookkeeping and structure tests only; no translated sample or result files generated',realCompletedTurns:original.rows.filter(t=>t.status==='MEASURED_COMPLETED_TURN').map(t=>({turnId:t.turnId,stage:t.stage,model:t.model,effort:t.effort,usage:t.usage,requestCount:t.requests.length})),tests:results};
await writeFile(resolve(root,dir+'method-validation.json'),JSON.stringify(report,null,2)+'\n','utf8');
console.log(JSON.stringify(report,null,2));
